void mostrarArtePersonaje(TipoHabilidadEspecial habilidad) {
    switch (habilidad) {
        case HABILIDAD_CRITICO_GRUPAL:
            mostrarArteASCII(arteIsaac_ptr, (int) (sizeof(arteIsaac_ptr) / sizeof(arteIsaac_ptr[0])));
            break;
        case HABILIDAD_DEFENSA_GRUPAL:
            mostrarArteASCII(arteDante_ptr, (int) (sizeof(arteDante_ptr) / sizeof(arteDante_ptr[0])));
            break;
        case HABILIDAD_CURACION_GRUPAL:
            mostrarArteASCII(arteFrieren_ptr, (int) (sizeof(arteFrieren_ptr) / sizeof(arteFrieren_ptr[0])));
            break;
        default:
            break;
    }
}

